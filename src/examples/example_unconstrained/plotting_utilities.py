SEED = 20251028
NP_HIST_OPTIONS = {"bins": 50, "density": True}
PLT_HIST_OPTIONS = {"bins": 50, "density": True, "histtype": "step"}


@dataclass
class Experiment_Uncon:
    """
    Experimental hyper-parameters for an unconstrained SCP experiment.

    Attributes
    ----------
    Q : Callable[..., np.ndarray]
        Map from Lambda x U --> D. Not the augmented version.
    num_inputs : int
        The number of lambda_i, u_i pairs to draw in order to generate q_i
        observations
    SCP_prior_count : int
        Number of prior points to draw from Lambda x U in SCP algorithm, for
        reweighing via importance sampling.
    SCP_lambda_grid_res : int
        The number of bins to split each axis of Lambda x U into in the SCP
        algorithm.
    SCP_D_grid_res : int
        The number of bins to split each axis of D x U into in the SCP
        algorithm.
    """

    Q: Callable[..., np.ndarray]
    num_inputs: int
    SCP_prior_count: int
    SCP_lambda_grid_res: int
    SCP_D_grid_res: int


def generate_example_data_uncon(
    domain: Domain,
    distributions: Distributions,
    expt_uncon: Experiment_Uncon,
    plot_options: PlotOptions,
    seed: int,
) -> None:
    """
    Run an unconstrained SCP.

    This function generates synthetic data {q_i} generated by evaluations
    Q(lambda_i, u_i), inputs the q_i into the SCP algorithm. Various data
    quantities are then saved for plotting, stored in the data/ folder.

    Parameters
    ----------
    domain : Domain
        Dataclass for Lambda and U specifications
    distributions : Distribution
        Dataclass for TGD and prior specifications.
    expt_uncon : Experiment_Uncon
        Dataclass for experimental hyper-parameters for unconstrained SCP.
    plot_options : PlotOptions
        Dataclass for plot and file-naming specifications.
    seed : int
        For reproducibility.

    Notes
    -----
    Carefully note the use of different seeds everywhere intentionally
    """

    def next_seed(_rng: np.random.Generator) -> int:
        """Use a RNG to generate another new seed.

        Returns
        -------
        int
        """
        return int(_rng.integers(0, 2**63 - 1))

    rng = np.random.default_rng(seed)
    tgd_seed = next_seed(rng)
    scp_seed = next_seed(rng)
    print("Beginning unconstrained SCP:")

    joint_tgd_vals = sample_distr(
        expt_uncon.num_inputs, tgd_seed, distributions.joint_tgd
    )

    lambda_tgd_vals = joint_tgd_vals[:, :-1]
    u_tgd_vals = joint_tgd_vals[:, -1]

    q_vals = apply_map(joint_tgd_vals, expt_uncon.Q)
    print(f"1. Synthetically generating {len(q_vals):,} obs. in D.")

    print(
        f"2. Running unconstrained SCP with non-augmented Q. Using {len(q_vals):,} obs., and resampling {expt_uncon.SCP_prior_count:,} prior samples."
    )
    unconstrained_prob_df, _ = empirical_scp(
        q_vals,
        expt_uncon.SCP_prior_count,
        expt_uncon.SCP_D_grid_res,
        expt_uncon.Q,
        distributions.joint_prior,
        domain.input_mins,
        domain.input_maxes,
        expt_uncon.SCP_lambda_grid_res,
        scp_seed,
    )

    data_dir = Path(f"data/example_{plot_options.folder_name}")
    data_dir.mkdir(exist_ok=True)

    np.savez(
        data_dir / f"{plot_options.expt_name}_arrays.npz",
        lambda_tgd_vals=lambda_tgd_vals,
        u_tgd_vals=u_tgd_vals,
        q_vals=q_vals,
    )

    unconstrained_prob_df.to_csv(
        data_dir / f"{plot_options.expt_name}_prob_df.csv", index=False
    )


def create_uncon_U_marginal_plots(
    ax: Axes,
    tgd_vals: np.ndarray,
    scp_df_uncon: pd.DataFrame,
    unpaired_scp_df_con: pd.DataFrame,
) -> None:
    """
    Plot U marginals from an SCP experiment.

    Adds to a subplot a histogram or step plot of the U TGD values, the U
    marginals from an unconstrained SCP, and one from an unpaired, constrained
    SCP that uses Sinkhorn.

    Parameters
    ----------
    ax : Axes
        Matplotlib axis
    tgd_vals : (N, ) numpy array
        One-dimensional U values from the marginal TGD. All values will be used
        for the plot.
    scp_df_uncon, unpaired_scp_df_con : pd.DataFrame
        A dataframe for the SCP solution on Lambda x U, either constrained or
        unconstrained.
    """
    scp_u_marginal_df_uncon = marginalize_out_lambda(scp_df_uncon)
    unpaired_scp_u_marginal_df_con = marginalize_out_lambda(unpaired_scp_df_con)

    tgd_counts, tgd_edges = np.histogram(tgd_vals, **NP_HIST_OPTIONS)
    ax.stairs(values=tgd_counts, edges=tgd_edges, label="TGD")

    # Add the unconstrained SCP U marginal
    u_bin_edges, probs = create_histogram_from_SCP_U_marginal(scp_u_marginal_df_uncon)
    ax.stairs(values=probs, edges=u_bin_edges, label="Unconst. Sol.")

    # Add the unpaired, constrained SCP U marginal
    u_bin_edges, probs = create_histogram_from_SCP_U_marginal(
        unpaired_scp_u_marginal_df_con
    )
    ax.stairs(values=probs, edges=u_bin_edges, label="Const. Sol.")

    ax.set_yticks([])
    ax.set_xlabel(r"$U$", fontsize=13)
    ax.set_title(r"$U$ Marginals, Actual versus SCP")

    # Redraw the legend to be a line, not a box
    custom_lines = [
        Line2D([0], [0], color="C0", lw=2),
        Line2D([0], [0], color="C1", lw=2),
        Line2D([0], [0], color="C2", lw=2),
    ]
    # Get axis labels to avoid manually typing them in
    _, stair_labels = ax.get_legend_handles_labels()
    ax.legend(
        handles=custom_lines, labels=stair_labels, loc="upper right", handlelength=1
    )


def create_uncon_D_marginal_plots(
    ax: Axes,
    tgd_pushforward_vals: np.ndarray,
    scp_df_uncon: pd.DataFrame,
    unpaired_scp_df_con: pd.DataFrame,
    Q: Callable[..., np.ndarray],
    D_min: float,
    D_max: float,
) -> None:
    """
    Plot D marginals from an SCP experiment.

    Adds to a subplot a histogram or step plot of the TGD pushforward values,
    and both SCP pushforwards.

    Parameters
    ----------
    ax : Axes
        Matplotlib axis
    tgd_pushforward_vals : (N, ) numpy array
        One-dimensional D values from the marginal TGD. All values will be used
        for the plot.
    scp_df_uncon : pd.DataFrame
        Unconstrained SCP solution
    unpaired_scp_df_con : pd.DataFrame
        Unpaired, constrained SCP solution
    Q : Callable[..., np.ndarray]
        The non-augmented map on Lambda x U.
    D_min, D_max : float
        x-axis limits
    """
    ax.hist(
        tgd_pushforward_vals, **PLT_HIST_OPTIONS, label=r"Observed $P_{\mathcal{D}}$"
    )

    input_sample_uncon = np.column_stack(sample_from_SCP(scp_df_uncon, 2000, SEED))
    pushforward_sample_uncon = apply_map(input_sample_uncon, Q)

    ax.hist(pushforward_sample_uncon, **PLT_HIST_OPTIONS, label="Unconst. Push.")

    input_sample_con = np.column_stack(sample_from_SCP(unpaired_scp_df_con, 2000, SEED))
    pushforward_sample_con = apply_map(input_sample_con, Q)

    ax.hist(pushforward_sample_con, **PLT_HIST_OPTIONS, label="Const. Push.")

    # Redraw the legend to be a line, not a box
    custom_lines = [
        Line2D([0], [0], color="C0", lw=2),
        Line2D([0], [0], color="C1", lw=2),
        Line2D([0], [0], color="C2", lw=2),
    ]
    # Get axis labels to avoid manually typing them in
    _, hist_labels = ax.get_legend_handles_labels()
    ax.legend(handles=custom_lines, labels=hist_labels, handlelength=1)

    ax.set_xlim(D_min, D_max)
    ax.xaxis.set_major_locator(MaxNLocator(5))
    ax.set_yticks([])
    ax.set_xlabel(r"$\mathcal{D}$", fontsize=13)
    ax.set_title(r"$\mathcal{D}$ Marginals from Pushforwards")


def create_uncon_example_plots(
    domain: Domain,
    expt_uncon: Experiment_Uncon,
    plot_options_uncon: PlotOptions,
    plot_options_con: PlotOptions,
) -> None:
    """
    Make unconstrained experiment plots.

    Reads in data from a Sinkhorn/SCP experiment and creates a 4x4 plot that
    summarizes the D and U marginals, the Sinkhorn solution, and the SCP
    solution. The Sinkhorn solution plot also shows some samples from this joint
    distribution, and the SCP solution plot shows a plot of some of the Lambda
    TGD points.

    Plots are saved in the plots/ folder.

    Parameters
    ----------
    domain : Domain
        Dataclass for Lambda and U specifications
    expt_uncon: Experiment_Uncon
        Dataclass for experimental hyper-parameters for unconstrained SCP.
    plot_options_uncon : PlotOptions
        Dataclass for unconstrained SCP's plot and filename related
        specifications
    plot_options_con : PlotOptions
        Dataclass for constrained (with Sinkhorn) plot and file name related
        specifications
    """
    rng = np.random.default_rng(seed=SEED)

    data_dir_uncon = Path(f"data/example_{plot_options_uncon.folder_name}")
    data_dir_con = Path(f"data/example_{plot_options_con.folder_name}")

    data_uncon = np.load(data_dir_uncon / f"{plot_options_uncon.expt_name}_arrays.npz")

    # We can use the same sample of Lambda, U TGD vals for both
    # constrained/unconstrained, as well as Q from the pushforward
    lambda_tgd_vals = data_uncon["lambda_tgd_vals"]
    lambda_tgd_subset = rng.choice(
        lambda_tgd_vals, size=plot_options_uncon.scatter_count, replace=False
    )
    q_vals = data_uncon["q_vals"]
    u_tgd_vals = data_uncon["u_tgd_vals"]

    scp_df_uncon = pd.read_csv(
        data_dir_uncon / f"{plot_options_uncon.expt_name}_prob_df.csv"
    )
    unpaired_scp_df_con = pd.read_csv(
        data_dir_con / f"unpaired_{plot_options_con.expt_name}_prob_df.csv"
    )

    fig, axes = plt.subplots(
        2, 2, figsize=plot_options_uncon.figsize, layout="constrained"
    )
    fig.get_layout_engine().set(w_pad=0.08, h_pad=0.1, wspace=0, hspace=0.05)  # type: ignore

    ax_U, ax_D, ax_SCP_uncon, ax_SCP_con = axes.ravel()

    u_q_tgd_sample = rng.choice(expt_uncon.num_inputs, size=10000, replace=True)

    create_uncon_U_marginal_plots(
        ax_U, u_tgd_vals[u_q_tgd_sample], scp_df_uncon, unpaired_scp_df_con
    )

    create_uncon_D_marginal_plots(
        ax_D,
        q_vals[u_q_tgd_sample],  # Same for both uncon/con
        scp_df_uncon,
        unpaired_scp_df_con,
        expt_uncon.Q,  # Note same Q for both uncon/con
        plot_options_uncon.D_min,  # Same for both uncon/con
        plot_options_uncon.D_max,  # Same for both uncon/con
    )

    marginal_scp_df_uncon = marginalize_out_U(scp_df_uncon)
    unpaired_marginal_scp_df_con = marginalize_out_U(unpaired_scp_df_con)

    scp_norm = PowerNorm(
        gamma=1,
        vmin=0,
        vmax=max(
            marginal_scp_df_uncon["prob"].max(),
            unpaired_marginal_scp_df_con["prob"].max(),
        ),
    )

    create_SCP_Lambda_plot(
        ax_SCP_uncon,
        marginal_scp_df_uncon,
        lambda_tgd_subset,
        scp_norm,
        domain.lambda_mins,
        domain.lambda_maxes,
    )
    ax_SCP_uncon.set_title(r"Unconstrained SCP Marginalized over $\Lambda$")
    ax_SCP_uncon.text(8.5, -9, r"$\Lambda$", color="white", fontsize=15, weight="bold")

    create_SCP_Lambda_plot(
        ax_SCP_con,
        unpaired_marginal_scp_df_con,
        lambda_tgd_subset,
        scp_norm,
        domain.lambda_mins,
        domain.lambda_maxes,
    )
    ax_SCP_con.set_title(r"Unpaired Constrained SCP Marginalized over $\Lambda$")
    ax_SCP_con.text(8.5, -9, r"$\Lambda$", color="white", fontsize=15, weight="bold")

    # Turn off titles for publication purposes
    for ax in axes.ravel():
        ax.tick_params(labelsize=12)
        ax.set_title("")

    out_path = Path(
        f"plots/example_{plot_options_con.folder_name}/{plot_options_uncon.expt_name}.pdf"
    )
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, dpi=plot_options_uncon.dpi)
    plt.close(fig)
