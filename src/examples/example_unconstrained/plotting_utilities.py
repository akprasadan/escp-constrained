from matplotlib.ticker import MaxNLocator

from src.data_processing import marginalize_out_lambda, marginalize_out_U
from src.estimate_functions import empirical_scp
from src.examples.data_generation_utilities import (
    Distributions,
    Domain,
    PlotOptions,
    create_histogram_from_SCP_U_marginal,
)
