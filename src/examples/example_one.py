plt.rcParams.update({"pdf.fonttype": 42, "text.usetex": True})

SEED = 20251028
MESH_OPTIONS = dict(shading="auto", rasterized=True)
SCATTERPLOT_OPTIONS = dict(s=8, alpha=0.9, edgecolors="black", linewidths=0.1)
HIST_OPTIONS = dict(alpha=0.8, bins=40)


def generate_example_one_data(
    domain: Domain, expt: Experiment, plot_options: PlotOptions
) -> None:
    """
    This function generates synthetic data {q_i} generated by evaluations Q(lambda_i, u_i), then with
    an independent sample {u_j}, fits a joint distribution on D x U using Sinkhorn algorithm.
    It then samples (q_i, u_i) from this joint distribution and feeds it into the SCP algorithm.
    Various data quantities are then saved for plotting, stored in the data/ folder.

    Parameters
    -----------
    domain : Domain
        Dataclass for Lambda and U specifications
    expt: Experimental
        Dataclass for experimental hyper-parameters for Sinkhorn and SCP
    plot_options : PlotOptions
        Data class for plot-related information
    """
    rng = np.random.default_rng(seed=SEED)
    lambda_tgd = rng.multivariate_normal(
        domain.lambda_mean,
        domain.lambda_cov,
        expt.num_inputs,
    )  # (N, 2)
    lambda_tgd_subset = rng.choice(
        lambda_tgd, size=plot_options.num_points_per_scatter, replace=False
    )

    u_tgd = rng.normal(domain.U_mean, domain.U_sd, expt.num_inputs)  # (N, )
    lambda_u_tgd = np.hstack((lambda_tgd, u_tgd[:, None]))  # (N, 3)

    q_vals = apply_map(lambda_u_tgd, expt.Q)  # (N, 3) --> (N, 1)

    u_indep = rng.normal(
        domain.U_mean,
        domain.U_sd,
        expt.num_indep_u_inputs,
    )  # (N', 1)
    lambda_prior = lambda rng, J: uniform_lambda_sampler(
        domain.lambda_mins, domain.lambda_maxes, rng, J
    )
    # Do NOT use u_tgd, we are simulating unpaired q and u data.
    sinkhorn_sol, u_grid, q_grid, _, _ = run_sinkhorn(
        q_vals,
        u_indep,
        expt.Q,
        lambda_prior,
        expt.sinkhorn_reg,
        domain.lambda_mins,
        domain.lambda_maxes,
        expt.num_monte_carlo_samples,
        expt.sinkhorn_grid_res_U,
        expt.sinkhorn_grid_res_D,
        SEED,
    )

    q_sinkhorn, u_sinkhorn = sample_joint_pairs(
        sinkhorn_sol,
        u_grid,
        q_grid,
        sample_size=expt.num_joint_pairs,
        seed=SEED,
    )

    joint_sample_subset = rng.choice(
        expt.num_joint_pairs,
        size=plot_options.num_points_per_scatter,
        replace=False,
    )
    q_sinkhorn_subset = q_sinkhorn[joint_sample_subset]
    u_sinkhorn_subset = u_sinkhorn[joint_sample_subset]

    lambda_u_prior = lambda rng, J: uniform_normal_sampler(
        domain.lambda_mins,
        domain.lambda_maxes,
        domain.U_mean,
        domain.U_sd,
        rng,
        J,
    )

    prob_df, _ = augmented_scp(
        q_sinkhorn,
        u_sinkhorn,
        expt.SCP_prior_count,
        expt.SCP_D_grid_res,
        expt.augmented_Q,
        lambda_u_prior,
        domain.lambda_u_mins,
        domain.lambda_u_maxes,
        expt.SCP_lambda_grid_res,
        SEED,
    )
    prob_df_marginal = marginalize_out_U(prob_df)

    data_dir = Path("data")
    data_dir.mkdir(exist_ok=True)

    np.savez(
        data_dir / f"{plot_options.expt_name}_arrays.npz",
        lambda_tgd_subset=lambda_tgd_subset,
        u_tgd=u_tgd,
        q_vals=q_vals,
        u_grid=u_grid,
        q_grid=q_grid,
        sinkhorn_sol=sinkhorn_sol,
        q_sinkhorn_subset=q_sinkhorn_subset,
        u_sinkhorn_subset=u_sinkhorn_subset,
    )

    prob_df_marginal.to_csv(
        data_dir / f"{plot_options.expt_name}_prob_df_marginal.csv",
        index=False,
    )


def create_example_one_plot(
    domain: Domain,
    expt: Experiment,
    plot_options: PlotOptions,
) -> None:
    """
    Reads in data saved after running generate_example_one_data() and creates a 4x4 plot
    that summarizes the D and U marginals, the Sinkhorn solution, and the SCP solution.
    The Sinkhorn solution plot also shows some samples from this joint distribution,
    and the SCP solution plot shows a plot of some of the Lambda TGD points.

    Plots are saved in the plots/ folder.

    Parameters
    -----------
    domain : Domain
        Dataclass for Lambda and U specifications
    expt: Experimental
        Dataclass for experimental hyper-parameters for Sinkhorn and SCP
    plot_options : PlotOptions
        Data class for plot-related information
    """
    data = np.load(f"data/{plot_options.expt_name}_arrays.npz")

    lambda_tgd_subset = data["lambda_tgd_subset"]
    u_tgd = data["u_tgd"]
    q_vals = data["q_vals"]
    u_grid = data["u_grid"]
    q_grid = data["q_grid"]
    sinkhorn_sol = data["sinkhorn_sol"]
    q_sinkhorn_subset = data["q_sinkhorn_subset"]
    u_sinkhorn_subset = data["u_sinkhorn_subset"]
    prob_df_marginal = pd.read_csv(
        f"data/{plot_options.expt_name}_prob_df_marginal.csv"
    )

    sinkhorn_joint_samples_df = pd.DataFrame(
        {"q": q_sinkhorn_subset, "u": u_sinkhorn_subset}
    )

    sinkhorn_joint_samples_df.to_csv(
        "data/joint_sinkhorn_data.csv", index=False
    )

    fig, axes = plt.subplots(2, 2, figsize=plot_options.figsize)
    plt.subplots_adjust(bottom=0.32, top=0.93, hspace=0.2, wspace=0.18)

    ax_D, ax_U, ax_sink, ax_scp = axes.ravel()

    ax_U.hist(
        u_tgd[0 : plot_options.num_points_histogram],
        color="orange",
        **HIST_OPTIONS,
    )
    ax_U.set_title(rf"Marginal on $U$: $P_U^t={plot_options.u_name}$.")
    ax_U.set_yticks([])
    ax_U.xaxis.set_major_locator(MaxNLocator(5))

    ax_D.hist(
        q_vals[0 : plot_options.num_points_histogram],
        color="purple",
        **HIST_OPTIONS,
    )
    ax_D.set_xlim(0, plot_options.D_max)
    ax_D.xaxis.set_major_locator(MaxNLocator(5))

    ax_D.set_title(
        rf"Marginal on $\mathcal{{D}}$ from $Q(\lambda_1,\lambda_2,u)={plot_options.map_name}$"
    )

    ax_D.set_yticks([])

    scp_norm = PowerNorm(gamma=0.5, vmin=0, vmax=prob_df_marginal["prob"].max())
    ax_scp.pcolormesh(
        *probs_to_mesh(prob_df_marginal),
        norm=scp_norm,
        cmap="viridis",
        **MESH_OPTIONS,
    )

    ax_scp.tick_params(labelsize=10)

    ax_scp.xaxis.set_major_locator(MaxNLocator(5))
    ax_scp.yaxis.set_major_locator(MaxNLocator(5))

    ax_scp.scatter(
        lambda_tgd_subset[:, 0],
        lambda_tgd_subset[:, 1],
        color="coral",
        **SCATTERPLOT_OPTIONS,
    )
    ax_scp.set_xlim(domain.lambda_mins[0], domain.lambda_maxes[0])
    ax_scp.set_ylim(domain.lambda_mins[1], domain.lambda_maxes[1])
    ax_scp.set_title(r"SCP Sol. $\hat P_{\Lambda}^t$ ($U$ marginalized out)")
    ax_scp.text(
        8.5,
        -9,
        r"$\Lambda$",
        color="white",
        fontsize=15,
        weight="bold",
    )

    sink_norm = PowerNorm(gamma=0.5, vmin=0, vmax=sinkhorn_sol.max())
    ax_sink.pcolormesh(
        q_grid,
        u_grid,
        sinkhorn_sol,
        norm=sink_norm,
        cmap="cividis",
        **MESH_OPTIONS,
    )
    ax_sink.set_ylabel(r"$U$", labelpad=0, fontsize=12)
    ax_sink.set_xlabel(r"$\mathcal{D}$", labelpad=5, fontsize=12)
    ax_sink.tick_params(labelsize=10)

    ax_sink.scatter(
        x=q_sinkhorn_subset,
        y=u_sinkhorn_subset,
        color="lavender",
        **SCATTERPLOT_OPTIONS,
    )
    ax_sink.set_xlim(0, plot_options.D_max)
    ax_sink.set_ylim(float(domain.U_mins[0]), float(domain.U_maxes[0]))
    ax_sink.set_facecolor("#00204C")
    ax_sink.xaxis.set_major_locator(MaxNLocator(5))
    ax_sink.yaxis.set_major_locator(MaxNLocator(5))
    ax_sink.set_title(
        rf"Sinkhorn Solution $\Pi$ on $\mathcal{{D}}\times U$, $\epsilon={expt.sinkhorn_reg}$"
    )

    caption = (
        r"$\textbf{Procedure:}$\\"
        r"Consider $Q\colon\Lambda \times U\to\mathcal{D}$, where "
        rf"$\Lambda=[-10,10]^2$, $U=[{float(domain.U_mins[0]):.0f},{float(domain.U_maxes[0]):.0f}]$, "
        r"$D=Q(\Lambda\times U)$.\\"
        rf"Set $Q(\lambda_1,\lambda_2,u)={plot_options.map_name}$.\\"
        r"Take $P_{\Lambda}^t=\mathcal{N}((4,4),\mathrm{diag}(1,5))$, "
        rf"$P_U^t={plot_options.u_name}$.\\"
        r"(1) Draw $(\lambda_{1i},\lambda_{2i},u_i)\sim P_{\Lambda}^t\times P_U^t$. "
        r" A subset of the $(\lambda_{1i},\lambda_{2i})$ is plotted as points on bottom right plot.\\"
        r"(2) Compute $q_i=Q(\lambda_{1i},\lambda_{2i},u_i)$ (top left plot).\\"
        r"(3) Draw independent $u_j\sim P_U^t$ (top right plot).\\"
        rf"(4) Run Sinkhorn on $\{{q_i\}}_i$ and $\{{u_j\}}_j$ with "
        rf"$\epsilon={expt.sinkhorn_reg}$ to obtain "
        r"a joint distribution $\Pi$ on $\mathcal{D}\times U$ "
        r"(heatmap on bottom left plot).\\"
        r"(5) Draw $(q_k,u_k)\sim\Pi$ (subset shown on bottom left plot).\\"
        r"(6) Run SCP using "
        r"$\tilde Q(\lambda_1,\lambda_2,u)=[Q(\lambda_1,\lambda_2,u),u]$ and the $(q_k, u_k).$ "
        rf"Use prior $\mathrm{{Unif}}[-10,10]^2 \times {plot_options.u_name}$ "
        r"for $\Lambda\times U$.\\"
        r"(7) Take SCP solution $\hat P_{\Lambda\times U}$ and marginalize out $U$ "
        r"to get $\hat P_{\Lambda}$ (heatmap in bottom right plot)."
    )

    fig.text(0.05, 0.05, caption, ha="left", va="bottom", fontsize=12)

    out_path = Path(f"plots/{plot_options.expt_name}.pdf")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, dpi=plot_options.dpi)
    plt.close(fig)


